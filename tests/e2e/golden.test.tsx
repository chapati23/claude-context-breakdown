// The terminal pane as a person reads it, compared line by line with the
// goldens in golden.ts. Levels 1, 2 (Tool results) and 3 (one Read result),
// at 45 and 88 columns, with and without the keyboard. Then the terminal's
// band in an early session of a 1M window, at its true scale, before and
// after `/ctx` first opens the pane. The marks show the
// ring (⟦ ⟧), off controls (⟪ ⟫) and dim parts (⟨ ⟩); see flatten in helpers.ts.
//
// When a drawing changes on purpose, the test fails and prints the whole
// golden module between GOLDEN-BEGIN and GOLDEN-END. To take it, run from
// the mod's folder:
//
//   claude plugin test . 2>&1 | sed -n '/^GOLDEN-BEGIN$/,/^GOLDEN-END$/p' | sed '1d;$d' > tests/e2e/golden.ts.new
//   [ -s tests/e2e/golden.ts.new ] && mv tests/e2e/golden.ts.new tests/e2e/golden.ts || rm tests/e2e/golden.ts.new
//
// The second line keeps golden.ts when the run printed no golden module.
// Then read the diff of golden.ts before you keep it. (A test here cannot
// read or write files or the environment, so there is no UPDATE switch.)

import { expect, test } from 'claude-code/testing'

import { BAND, NOTES, barRowOf, earlySession } from '../fixtures'
import { GOLDEN } from './golden'
import { flatten, mountPane, real, session } from './helpers'

/**
 * Thirty MCP servers whose tools are not loaded, as in the mockups: eight
 * named ones, then smaller ones. `[name, tools, tokens]`, the tokens shared
 * evenly over the tools.
 */
const SERVERS: readonly (readonly [string, number, number])[] = [
  ['claude_ai_Vercel', 265, 171_000],
  ['claude_ai_Notion', 78, 80_000],
  ['grafana', 79, 32_000],
  ['claude_ai_Slack', 27, 27_000],
  ['cmux-cua', 39, 23_000],
  ['github', 42, 16_000],
  ['claude_ai_Google_Drive', 16, 9800],
  ['claude-in-chrome', 20, 9400],
  ...Array.from({ length: 22 }, (_, k) => [`server-${k + 1}`, 6 - (k % 5), 2200 - k * 50] as const),
]

/**
 * The critique's session, plus one short Read so level 3 fits a golden, and
 * the tools of thirty servers that are not loaded, so level 1 shows Not
 * loaded and the list of servers has two pages.
 */
function goldenSession() {
  const opts = real()
  const breakdown = opts.usage!.context.breakdown!
  const mcpTools = SERVERS.flatMap(([serverName, tools, tokens]) =>
    Array.from({ length: tools }, (_, k) => ({
      name: `mcp__${serverName}__t${k}`,
      serverName,
      // Whole tokens that add up to the server's figure.
      tokens: Math.floor(tokens / tools) + (k < tokens % tools ? 1 : 0),
      isLoaded: false,
    })),
  )
  const deferred = SERVERS.reduce((sum, [, , tokens]) => sum + tokens, 0)
  const categories = [
    ...breakdown.categories,
    { name: 'MCP tools (deferred)', tokens: deferred, kind: 'deferred' as const, color: 'inactive', isDeferred: true },
    { name: 'System tools (deferred)', tokens: 32_000, kind: 'deferred' as const, color: 'inactive', isDeferred: true },
  ]

  return {
    ...opts,
    usage: { ...opts.usage!, context: { ...opts.usage!.context, breakdown: { ...breakdown, categories, mcpTools } } },
    messages: [
      ...(opts.messages ?? []),
      { role: 'assistant', content: [{ type: 'tool_use', id: 'tu1', name: 'Read', input: { file_path: NOTES } }] },
      { role: 'user', content: [{ type: 'tool_result', tool_use_id: 'tu1', content: '     1\talpha\n     2\tbeta\n' }] },
    ],
  }
}

/** The presses from level 1 to each level, and back. */
const LEVELS = [
  { name: 'level1', path: [] },
  { name: 'level2-tool-results', path: ['row-tool-results'] },
  { name: 'level2-not-loaded', path: ['row-not-loaded'] },
  { name: 'level3-read', path: ['row-tool-results', 'item-r:tu1'] },
] as const

/** Prints to the test run's output (the types of this mod declare no console). */
function log(text: string): void {
  const host = globalThis as unknown as { console: { log: (text: string) => void } }
  host.console.log(text)
}

/** golden.ts as it would be written for these drawings. */
function goldenModule(drawings: Record<string, string[]>): string {
  const entries = Object.entries(drawings).map(
    ([key, lines]) => `  ${JSON.stringify(key)}: [\n${lines.map(line => `    ${JSON.stringify(line)},\n`).join('')}  ],\n`,
  )

  return [
    '// Generated by golden.test.tsx: see the note at its top before you edit.',
    '// One entry per level, width and focus: the terminal pane, flattened with marks.',
    'export const GOLDEN: Record<string, readonly string[]> = {',
    ...entries.map(entry => entry.trimEnd()),
    '}',
  ].join('\n')
}

test('the terminal pane at levels 1, 2 and 3 reads as its goldens', async ($, on) => {
  const w = await session($, on, goldenSession())
  const drawings: Record<string, string[]> = {}

  for (const level of LEVELS) {
    for (const columns of [45, 88]) {
      for (const isFocused of [true, false]) {
        const ui = await mountPane($, 'terminal', { columns, isFocused })
        for (const key of level.path) {
          await ui.press({ key })
        }
        drawings[`${level.name}/${columns}/${isFocused ? 'focused' : 'unfocused'}`] = flatten(await ui.drawn(), { marks: true, columns })
        // Back to level 1, so the next mount starts there.
        for (const _ of level.path) {
          await ui.press({ key: 'back' })
        }
        await ui.unmount()
      }
    }
  }

  // Level 1 with the column added: the person's prompt, then a turn that
  // adds a 14,000-character Bash result and a 1,900-character reply.
  await $.prompt.submit({ text: 'go on', wait: false, origin: { kind: 'composer' } })
  await w.clock.advance(0)
  const extra = 16_000
  const context = w.usage.context
  const breakdown = context.breakdown!
  w.usage = {
    ...w.usage,
    context: {
      ...context,
      tokens: context.tokens! + extra,
      breakdown: {
        ...breakdown,
        categories: breakdown.categories.map(one => (one.name === 'Messages' ? { ...one, tokens: one.tokens + extra } : one)),
      },
    },
  }
  w.messages = [
    ...(w.messages ?? []),
    { role: 'assistant', content: [{ type: 'tool_use', id: 'tu2', name: 'Bash', input: { command: 'ls' } }] },
    { role: 'user', content: [{ type: 'tool_result', tool_use_id: 'tu2', content: 'o'.repeat(14_000) }] },
    { role: 'assistant', content: [{ type: 'text', text: 'c'.repeat(1900) }] },
  ]
  await $.session.measure({ context: w.usage.context, rateLimits: [], changed: ['context'] })
  await w.clock.advance(0)
  const added = await mountPane($, 'terminal', { columns: 88, isFocused: true })
  drawings['level1-added/88/focused'] = flatten(await added.drawn(), { marks: true, columns: 88 })
  await added.unmount()

  // The band in an early session of a 1M window: 69k used, mostly free
  // space at the bar's true scale. At 150 and 90 terminal columns (the band is 5 narrower),
  // with the hint until `/ctx` opens the pane, then with the legend.
  const early = earlySession()
  w.usage = early.usage
  w.messages = early.messages
  await $.session.measure({ context: w.usage.context, rateLimits: [], changed: ['context'] })
  await w.clock.advance(0)
  const drawBand = async (state: string) => {
    for (const columns of [145, 85]) {
      const band = await $.ui.mount({ ...BAND, surface: 'terminal', props: { ...BAND.props, bodyColumns: columns } })
      drawings[`band-1m-69k/${columns}/${state}`] = flatten(barRowOf(await band.drawn()), { marks: true, columns })
      await band.unmount()
    }
  }
  await drawBand('hint')
  await $.command.run({ command: 'ctx', args: '', origin: { kind: 'composer' }, presentation: { isFullscreen: true, columns: 120 } })
  await drawBand('legend')

  const keys = new Set([...Object.keys(drawings), ...Object.keys(GOLDEN)])
  const changed = [...keys].filter(key => JSON.stringify(drawings[key]) !== JSON.stringify(GOLDEN[key]))
  if (changed.length > 0) {
    log(`goldens changed: ${changed.join(', ')}`)
    log(`GOLDEN-BEGIN\n${goldenModule(drawings)}\nGOLDEN-END`)
  }
  expect(changed).toEqual([])
  expect(drawings).toEqual(GOLDEN as Record<string, string[]>)
})
