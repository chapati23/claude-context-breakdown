// The terminal pane as a person reads it, compared line by line with the
// goldens in golden.ts. Levels 1, 2 (Tool results) and 3 (one Read result),
// at 45 and 88 columns, with and without the keyboard. The marks show the
// ring (⟦ ⟧), off controls (⟪ ⟫) and dim parts (⟨ ⟩); see flatten in helpers.ts.
//
// When a drawing changes on purpose, the test fails and prints the whole
// golden module between GOLDEN-BEGIN and GOLDEN-END. To take it, run from
// the mod's folder:
//
//   claude plugin test . 2>&1 | sed -n '/^GOLDEN-BEGIN$/,/^GOLDEN-END$/p' | sed '1d;$d' > tests/e2e/golden.ts.new
//   [ -s tests/e2e/golden.ts.new ] && mv tests/e2e/golden.ts.new tests/e2e/golden.ts || rm tests/e2e/golden.ts.new
//
// The second line keeps golden.ts when the run printed no golden module.
// Then read the diff of golden.ts before you keep it. (A test here cannot
// read or write files or the environment, so there is no UPDATE switch.)

import { expect, test } from 'claude-code/testing'

import { NOTES } from '../fixtures'
import { GOLDEN } from './golden'
import { flatten, mountPane, real, session } from './helpers'

/** The critique's session, plus one short Read so level 3 fits a golden. */
function goldenSession() {
  const opts = real()

  return {
    ...opts,
    messages: [
      ...(opts.messages ?? []),
      { role: 'assistant', content: [{ type: 'tool_use', id: 'tu1', name: 'Read', input: { file_path: NOTES } }] },
      { role: 'user', content: [{ type: 'tool_result', tool_use_id: 'tu1', content: '     1\talpha\n     2\tbeta\n' }] },
    ],
  }
}

/** The presses from level 1 to each level, and back. */
const LEVELS = [
  { name: 'level1', path: [] },
  { name: 'level2-tool-results', path: ['row-tool-results'] },
  { name: 'level3-read', path: ['row-tool-results', 'item-r:tu1'] },
] as const

/** Prints to the test run's output (the types of this mod declare no console). */
function log(text: string): void {
  const host = globalThis as unknown as { console: { log: (text: string) => void } }
  host.console.log(text)
}

/** golden.ts as it would be written for these drawings. */
function goldenModule(drawings: Record<string, string[]>): string {
  const entries = Object.entries(drawings).map(
    ([key, lines]) => `  ${JSON.stringify(key)}: [\n${lines.map(line => `    ${JSON.stringify(line)},\n`).join('')}  ],\n`,
  )

  return [
    '// Generated by golden.test.tsx: see the note at its top before you edit.',
    '// One entry per level, width and focus: the terminal pane, flattened with marks.',
    'export const GOLDEN: Record<string, readonly string[]> = {',
    ...entries.map(entry => entry.trimEnd()),
    '}',
  ].join('\n')
}

test('the terminal pane at levels 1, 2 and 3 reads as its goldens', async ($, on) => {
  await session($, on, goldenSession())
  const drawings: Record<string, string[]> = {}

  for (const level of LEVELS) {
    for (const columns of [45, 88]) {
      for (const isFocused of [true, false]) {
        const ui = await mountPane($, 'terminal', { columns, isFocused })
        for (const key of level.path) {
          await ui.press({ key })
        }
        drawings[`${level.name}/${columns}/${isFocused ? 'focused' : 'unfocused'}`] = flatten(await ui.drawn(), { marks: true, columns })
        // Back to level 1, so the next mount starts there.
        for (const _ of level.path) {
          await ui.press({ key: 'back' })
        }
        await ui.unmount()
      }
    }
  }

  const keys = new Set([...Object.keys(drawings), ...Object.keys(GOLDEN)])
  const changed = [...keys].filter(key => JSON.stringify(drawings[key]) !== JSON.stringify(GOLDEN[key]))
  if (changed.length > 0) {
    log(`goldens changed: ${changed.join(', ')}`)
    log(`GOLDEN-BEGIN\n${goldenModule(drawings)}\nGOLDEN-END`)
  }
  expect(changed).toEqual([])
  expect(drawings).toEqual(GOLDEN as Record<string, string[]>)
})
